const CENTROID_INDEX = new Map<string, CityCentroid>(
  US_CITY_CENTROIDS.map((entry) => [
    `${entry.city.toLowerCase()}|${entry.state.toLowerCase()}`,
    entry,
  ]),
);

export function lookupCityCoordinates(
  city: string,
  state: string,
): { latitude: number; longitude: number } | null {
  const match = CENTROID_INDEX.get(`${city.toLowerCase()}|${state.toLowerCase()}`);
  return match ? { latitude: match.latitude, longitude: match.longitude } : null;
}
